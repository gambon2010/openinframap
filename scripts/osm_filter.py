#!/usr/bin/env python3
"""
Print an osmium tags-filter expression file matching every object the imposm
mapping (imposm/*.py) imports.

Pre-filtering a Geofabrik extract with these expressions shrinks it by ~95%
without changing what ends up in the database, which makes the imposm import
much faster and far less hungry for disk.

Usage:
    python3 scripts/osm_filter.py > filter.txt
    osmium tags-filter in.osm.pbf -e filter.txt -o out.osm.pbf
"""

import contextlib
import io
import json
import runpy
import sys
from pathlib import Path

IMPOSM_DIR = Path(__file__).resolve().parent.parent / "imposm"


def load_mapping() -> dict:
    sys.path.insert(0, str(IMPOSM_DIR))
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        runpy.run_path(str(IMPOSM_DIR / "main.py"), run_name="__main__")
    return json.loads(out.getvalue())


# Which OSM object types each imposm geometry type is built from: n(odes),
# w(ays), r(elations). Areas come from closed ways and multipolygon relations.
OBJECT_TYPES = {
    "point": "n",
    "points": "n",
    "linestring": "w",
    "linestrings": "w",
    "polygon": "wr",
    "polygons": "wr",
    "relation": "r",
    "relation_member": "r",
}


def main() -> None:
    mapping = load_mapping()

    # (key, value) -> OSM object types needed; value None means "any value".
    needed: dict[tuple[str, str | None], set[str]] = {}
    for table in mapping["tables"].values():
        if "mapping" in table:
            by_type = {table["type"]: table["mapping"]}
        else:
            by_type = table["type_mappings"]
        for geometry_type, m in by_type.items():
            kinds = set(OBJECT_TYPES.get(geometry_type, "nwr"))
            for key, values in m.items():
                for value in values:
                    needed.setdefault((key, None if value == "__any__" else value), set()).update(kinds)

    # Group into one expression per (key, object types), e.g. "n/place=hamlet,village".
    groups: dict[tuple[str, str], list[str]] = {}
    any_value: dict[str, str] = {}
    for (key, value), kinds in needed.items():
        object_types = "".join(t for t in "nwr" if t in kinds)
        if value is None:
            any_value[key] = object_types
        else:
            groups.setdefault((key, object_types), []).append(value)

    print("# Generated by scripts/osm_filter.py from the imposm mapping. Do not edit.")
    for key, object_types in sorted(any_value.items()):
        print(f"{object_types}/{key}")
    for (key, object_types), values in sorted(groups.items()):
        if key in any_value:
            continue  # already matched for any value
        print(f"{object_types}/{key}={','.join(sorted(values))}")


if __name__ == "__main__":
    main()
